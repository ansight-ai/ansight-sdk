#!/usr/bin/env python3
"""Prepare pinned, disposable benchmark checkouts without modifying upstream refs."""

import argparse
import json
import plistlib
import subprocess
import sqlite3
from pathlib import Path
from xml.sax.saxutils import escape


SDK_ROOT = Path(__file__).resolve().parents[2]
SUITE = json.loads((SDK_ROOT / "test-apps/avalonia/suite.json").read_text())
SOURCES = SUITE["sources"]


def git(directory, *arguments):
    return subprocess.check_output(["git", "-C", str(directory), *arguments], text=True).strip()


def checkout(parent, name, source):
    destination = parent / name
    if not destination.exists():
        subprocess.run(["git", "clone", "--filter=blob:none", "--no-checkout", source["url"], str(destination)], check=True)
        subprocess.run(["git", "-C", str(destination), "checkout", "--detach", source["revision"]], check=True)

    actual = git(destination, "rev-parse", "HEAD")
    if actual != source["revision"]:
        raise RuntimeError(f"{destination} is at {actual}; expected {source['revision']}. Existing work was preserved.")

    return destination


def replace_once(path, old, new):
    text = path.read_text(encoding="utf-8-sig")
    if new in text:
        return
    if text.count(old) != 1:
        raise RuntimeError(f"Expected exactly one integration anchor in {path}")
    path.write_text(text.replace(old, new, 1))


def add_sdk_reference(path, database_path):
    project = escape(str(SDK_ROOT / "src/dotnet/Ansight.Avalonia/Ansight.Avalonia.csproj"), {'"': '&quot;'})
    targets = escape(str(SDK_ROOT / "src/dotnet/Ansight.Core/build/Ansight.targets"), {'"': '&quot;'})
    configuration = escape(str(SDK_ROOT / "test-apps/avalonia/BenchmarkConfiguration.cs"), {'"': '&quot;'})
    fixtures = escape(str(SDK_ROOT / "test-apps/avalonia/Fixtures/*.cs"), {'"': '&quot;'})
    database = escape(str(database_path), {'"': '&quot;'})
    integration = f'''  <!-- Ansight benchmark integration; generated by prepare_samples.py. -->
  <PropertyGroup>
    <AnsightBenchmarkToolsEnabled Condition="'$(Configuration)' == 'Debug'">true</AnsightBenchmarkToolsEnabled>
    <AnsightBenchmarkToolsEnabled Condition="'$(AnsightBenchmarkToolsEnabled)' == ''">false</AnsightBenchmarkToolsEnabled>
    <AnsightRemoteToolsPolicy Condition="'$(AnsightBenchmarkToolsEnabled)' == 'true'">AllowedWithWarnings</AnsightRemoteToolsPolicy>
    <AnsightRemoteToolsPolicy Condition="'$(AnsightBenchmarkToolsEnabled)' != 'true'">Disallowed</AnsightRemoteToolsPolicy>
    <DefineConstants Condition="'$(AnsightBenchmarkToolsEnabled)' == 'true'">$(DefineConstants);ANSIGHT_BENCHMARK_TOOLS</DefineConstants>
    <ImplicitUsings>enable</ImplicitUsings>
    <Nullable>enable</Nullable>
    <EmbedAssembliesIntoApk Condition="$([MSBuild]::GetTargetPlatformIdentifier('$(TargetFramework)')) == 'android'">true</EmbedAssembliesIntoApk>
    <SupportedOSPlatformVersion Condition="$([MSBuild]::GetTargetPlatformIdentifier('$(TargetFramework)')) == 'ios'">15.0</SupportedOSPlatformVersion>
  </PropertyGroup>
  <ItemGroup>
    <ProjectReference Include="{project}" />
    <Compile Include="{configuration}" Link="AnsightBenchmarkConfiguration.cs" />
    <Compile Include="{fixtures}" Link="AnsightBenchmark/%(Filename)%(Extension)" Condition="'$(AnsightBenchmarkToolsEnabled)' == 'true'" />
    <EmbeddedResource Include="{database}" LogicalName="AnsightBenchmark.database.db" Condition="'$(AnsightBenchmarkToolsEnabled)' == 'true'" />
  </ItemGroup>
  <Import Project="{targets}" />
</Project>'''
    text = path.read_text(encoding="utf-8-sig")
    marker = "  <!-- Ansight benchmark integration; generated by prepare_samples.py. -->"
    if marker in text:
        text = text[:text.index(marker)] + integration
        path.write_text(text)
    else:
        replace_once(path, "</Project>", integration)


def prepare_vignettes(repository, database_path):
    hosts = repository / "vignettes/_hosts"
    plist_path = hosts / "iOS/Info.plist"
    info = plistlib.loads(plist_path.read_bytes())
    info["MinimumOSVersion"] = "15.0"
    info["NSAppTransportSecurity"] = {"NSAllowsArbitraryLoads": True}
    plist_path.write_bytes(plistlib.dumps(info, sort_keys=False))
    replace_once(hosts / "Android/Application.cs", "    SupportsRtl = true)", "    SupportsRtl = true, UsesCleartextTraffic = true)")
    for platform, source_file in [("Android", "Application.cs"), ("iOS", "VignetteApplication.cs")]:
        add_sdk_reference(hosts / platform / f"Vignette.{platform}.props", database_path)
        path = hosts / platform / source_file
        replace_once(path, "using Avalonia;", "using Ansight.Avalonia;\nusing Avalonia;")
        bootstrap = "base.CustomizeAppBuilder(builder).WithInterFont().UseAnsight<VignetteApp>(options =>\n"
        configuration = "            Ansight.Avalonia.Benchmarks.BenchmarkConfiguration.Configure(options, typeof(VignetteApplication).Assembly));"
        previous = bootstrap + "            options.WithBundledHostConnection(typeof(VignetteApplication).Assembly));"
        if previous in path.read_text():
            replace_once(path, previous, bootstrap + configuration)
        else:
            replace_once(path, "base.CustomizeAppBuilder(builder).WithInterFont();", bootstrap + configuration)

    benchmarks = []
    for directory in sorted((repository / "vignettes").iterdir()):
        if not directory.is_dir() or directory.name.startswith("_"):
            continue
        heads = {}
        for platform in ["Android", "iOS"]:
            projects = list(directory.glob(f"*.{platform}/*.csproj"))
            if len(projects) != 1:
                raise RuntimeError(f"Expected exactly one {platform} head for {directory.name}")
            heads[platform.lower()] = str(projects[0].relative_to(repository))
        benchmarks.append({"id": directory.name, "source": "avalonia_vignettes", "projects": heads})

    if len(benchmarks) != 17:
        raise RuntimeError(f"Expected all 17 pinned vignettes; discovered {len(benchmarks)}")
    return benchmarks


def prepare_control_catalog(repository, database_path):
    replace_once(repository / "src/iOS/Avalonia.iOS/Avalonia.iOS.csproj",
                 "<TargetFrameworks>$(AvsCurrentMacCatalystTargetFramework);$(AvsCurrentIOSTargetFramework);$(AvsCurrentTvOSTargetFramework)</TargetFrameworks>",
                 "<TargetFrameworks>$(AvsCurrentMacCatalystTargetFramework);$(AvsCurrentIOSTargetFramework);$(AvsCurrentTvOSTargetFramework)</TargetFrameworks>\n"
                 "    <TargetFrameworks Condition=\"'$(AnsightAvaloniaMobileBenchmark)' == 'true'\">$(AvsCurrentIOSTargetFramework)</TargetFrameworks>")
    replace_once(repository / "samples/ControlCatalog.Android/Application.cs", "[Application]", "[Application(UsesCleartextTraffic = true)]")
    plist_path = repository / "samples/ControlCatalog.iOS/Info.plist"
    info = plistlib.loads(plist_path.read_bytes())
    info["NSAppTransportSecurity"] = {"NSAllowsArbitraryLoads": True}
    plist_path.write_bytes(plistlib.dumps(info, sort_keys=False))
    for platform, source_file, application_type in [
        ("Android", "Application.cs", "Application"),
        ("iOS", "AppDelegate.cs", "AppDelegate"),
    ]:
        head = repository / "samples" / f"ControlCatalog.{platform}"
        add_sdk_reference(head / f"ControlCatalog.{platform}.csproj", database_path)
        source = head / source_file
        replace_once(source, "using Avalonia;", "using Ansight.Avalonia;\nusing Avalonia;")
        replace_once(source, "return base.CustomizeAppBuilder(builder)",
                     "return base.CustomizeAppBuilder(builder)\n"
                     "                .UseAnsight<App>(options =>\n"
                     f"                    Ansight.Avalonia.Benchmarks.BenchmarkConfiguration.Configure(options, typeof({application_type}).Assembly))")

    return {
        "id": "control_catalog",
        "source": "Avalonia",
        "projects": {
            "android": "samples/ControlCatalog.Android/ControlCatalog.Android.csproj",
            "ios": "samples/ControlCatalog.iOS/ControlCatalog.iOS.csproj",
        },
        "buildProperties": {
            "AvaloniaSourceRoot": str(repository),
            "AvsSkipBuildingNextTargetFrameworks": "True",
            "AnsightAvaloniaMobileBenchmark": "true",
            "AvsCurrentIOSTargetFramework": "net10.0-ios",
        },
    }


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--output", type=Path, default=SDK_ROOT / ".ansight-validation/avalonia")
    parser.add_argument("--sdk-version", default="10.0.201")
    parser.add_argument("--workload-version", default="10.0.204")
    arguments = parser.parse_args()
    output = arguments.output.resolve()
    output.mkdir(parents=True, exist_ok=True)
    (output / "NuGet.Config").write_text('''<?xml version="1.0" encoding="utf-8"?>
<configuration>
  <packageSources><clear /><add key="nuget.org" value="https://api.nuget.org/v3/index.json" /></packageSources>
  <packageSourceMapping><clear /></packageSourceMapping>
</configuration>
''')
    fixture_directory = output / "fixtures"
    fixture_directory.mkdir(parents=True, exist_ok=True)
    database_path = fixture_directory / "database.db"
    database_path.unlink(missing_ok=True)
    with sqlite3.connect(database_path) as database:
        database.executescript((SDK_ROOT / "test-apps/avalonia/Fixtures/database.sql").read_text())
    upstream = output / "upstream"
    upstream.mkdir(parents=True, exist_ok=True)
    repositories = {name: checkout(upstream, name, source) for name, source in SOURCES.items()}
    toolchain = {"version": arguments.sdk_version, "rollForward": "latestPatch", "workloadVersion": arguments.workload_version}
    (repositories["avalonia_vignettes"] / "global.json").write_text(json.dumps({"sdk": toolchain}, indent=2) + "\n")
    benchmarks = prepare_vignettes(repositories["avalonia_vignettes"], database_path)
    benchmarks.insert(0, prepare_control_catalog(repositories["Avalonia"], database_path))
    for sample in ["Network", "FilesArtifacts"]:
        benchmarks.append({
            "id": "sample_" + sample.lower(),
            "source": "local",
            "projects": {platform.lower(): str(SDK_ROOT / "test-apps/avalonia/SampleApps" / f"{sample}.{platform}" / f"{sample}.{platform}.csproj") for platform in ["iOS", "Android"]},
            "buildProperties": {"AnsightBenchmarkDatabase": str(database_path)},
        })
    children = {child["id"]: child for child in SUITE["children"]}
    if {benchmark["id"] for benchmark in benchmarks} != set(children):
        raise RuntimeError("Prepared benchmarks do not match the source-controlled Avalonia suite children.")
    for benchmark in benchmarks:
        benchmark["appIds"] = children[benchmark["id"]]["appIds"]

    manifest = {
        "schemaVersion": 1,
        "suite": SUITE["suite"],
        "workspaceRoot": str(SDK_ROOT / "test-apps/avalonia"),
        "sources": SOURCES,
        "benchmarks": benchmarks,
        "platforms": ["ios", "android"],
        "vignetteBuildToolchain": toolchain,
        "validationStatus": "not_run",
    }
    manifest_path = output / "samples.json"
    manifest_path.write_text(json.dumps(manifest, indent=2) + "\n")
    print(json.dumps({"manifest": str(manifest_path), "benchmarkCount": len(benchmarks), "mobileTargets": len(benchmarks) * 2}))


if __name__ == "__main__":
    main()
